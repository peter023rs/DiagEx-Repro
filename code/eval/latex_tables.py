"""Render aggregate DataFrames to LaTeX fragments the paper ``\\input{}``s.

Two tables for the diagex evaluation:

* ``table2.tex`` — Phase 1 per-diagram accuracy (plan §5.1)
* ``table3.tex`` — Phase 2 per-diagram extraction (plan §5.2)

Conventions:

* booktabs (``\\toprule`` / ``\\midrule`` / ``\\bottomrule``) — paper class is
  IEEEtran, which has ``booktabs`` available.
* numbers formatted with 2 decimals; cost rounded to cents; latency to 1s.
* missing values rendered as ``--`` (Phase 2 edge F1 on partial-truth rows
  is the canonical case; cost/latency may be missing in cassette mode).
* fixture names escape underscore characters (``open100-1`` is fine; the
  legacy ``h2first1.pdf`` had no underscore either, so this is mostly
  defensive).
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

import pandas as pd

from eval.aggregate import PHASE1_FAMILIES


def _esc(s: Any) -> str:
    text = "" if s is None else str(s)
    return text.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def _fmt_score(v: Any) -> str:
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"{float(v):.2f}"


def _fmt_score_shaded(v: Any) -> str:
    """Like ``_fmt_score`` but shades cells whose displayed value is < 1.00.

    The threshold is on the *formatted* string so that a macro mean of e.g.
    0.998 (which rounds to ``1.00``) is not shaded.
    """
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    formatted = f"{float(v):.2f}"
    if formatted == "1.00":
        return formatted
    return f"\\cellcolor{{gray!20}}{formatted}"


def _fmt_money(v: Any) -> str:
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"\\$ {float(v):.2f}"


def _fmt_seconds(v: Any) -> str:
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"{float(v):.1f}"


def _fmt_minutes(v: Any) -> str:
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"{float(v):.1f}"


def _fmt_int(v: Any) -> str:
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"{int(v)}"


def _fmt_yn(v: Any) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    if isinstance(v, (int, float)):
        return "Y" if float(v) >= 0.5 else "N"
    return str(v)


# ---------------------------------------------------------------------------
# Table II — Phase 1 per-diagram accuracy
# ---------------------------------------------------------------------------


TABLE2_PREAMBLE = (
    "% Auto-generated by eval/latex_tables.py - do not edit by hand.\n"
    "\\begin{table}[t]\n"
    "\\centering\n"
    "\\setlength{\\tabcolsep}{3pt}\n"
    "\\caption{Phase 1 query accuracy per diagram and query family. "
    "Cells are F1 (set\\_match), 0/1 (other scoring kinds) averaged across "
    "$N=3$ trials. Cost / latency are per-query medians. "
    "The macro row weights all ten fixtures equally.}\n"
    "\\label{tab:phase1}\n"
    "\\begin{tabular}{lcccccrr}\n"
    "\\toprule\n"
    "Diagram & Inv. & Cnt. & Conn. & Ident. & Overall & Cost & Lat. \\\\\n"
    "\\midrule\n"
)
TABLE2_EPILOGUE = (
    "\\bottomrule\n"
    "\\end{tabular}\n"
    "\\end{table}\n"
)


def render_table2(wide: pd.DataFrame) -> str:
    """``wide`` comes from ``aggregate.phase1_per_fixture_wide``."""
    if wide.empty:
        return TABLE2_PREAMBLE + "\\multicolumn{8}{c}{(no Phase 1 results)} \\\\\n" + TABLE2_EPILOGUE

    body_lines: list[str] = []
    for _, row in wide.iterrows():
        is_macro = row["fixture"] == "macro"
        cells = [
            (f"\\textbf{{{_esc(row['fixture'])}}}" if is_macro else _esc(row["fixture"])),
            *[_fmt_score_shaded(row.get(fam)) for fam in PHASE1_FAMILIES],
            _fmt_score_shaded(row.get("overall")),
            _fmt_money(row.get("cost_median")),
            _fmt_seconds(row.get("latency_median")),
        ]
        line = " & ".join(cells) + " \\\\"
        if is_macro:
            body_lines.append("\\midrule")
        body_lines.append(line)

    return TABLE2_PREAMBLE + "\n".join(body_lines) + "\n" + TABLE2_EPILOGUE


# ---------------------------------------------------------------------------
# Table III — Phase 2 per-diagram extraction
# ---------------------------------------------------------------------------


TABLE3_PREAMBLE = (
    "% Auto-generated by eval/latex_tables.py - do not edit by hand.\n"
    "\\begin{table*}[t]\n"
    "\\centering\n"
    "\\caption{Phase 2 DEXPI extraction per diagram. "
    "OPC F1 and Edge F1 are N/A for inventory-only fixtures "
    "(no OPCs / edges labelled in ground truth); "
    "Y in the DEXPI column means the diagex DEXPI 2.0 round-trip validator accepts the output. "
    "The macro row weights all ten fixtures equally for the per-kind F1 columns "
    "and only the three full-truth fixtures for OPC F1 and edge F1.}\n"
    "\\label{tab:phase2}\n"
    "\\begin{tabular}{lrrrrrrrcrr}\n"
    "\\toprule\n"
    "Diagram & Entities & Equipment F1 & Instrument F1 & OPC F1 & Tag EM & Edge F1 & DEXPI & Cost & Minutes \\\\\n"
    "\\midrule\n"
)
TABLE3_EPILOGUE = (
    "\\bottomrule\n"
    "\\end{tabular}\n"
    "\\end{table*}\n"
)


def render_table3(per_fixture: pd.DataFrame) -> str:
    """``per_fixture`` comes from ``aggregate.phase2_per_fixture``."""
    if per_fixture.empty:
        return TABLE3_PREAMBLE + "\\multicolumn{10}{c}{(no Phase 2 results)} \\\\\n" + TABLE3_EPILOGUE

    body_lines: list[str] = []
    for _, row in per_fixture.iterrows():
        cells = [
            _esc(row["fixture"]),
            _fmt_int(row.get("entity_count_truth")),
            _fmt_score(row.get("phase2_equipment_f1")),
            _fmt_score(row.get("phase2_instrument_f1")),
            _fmt_score(row.get("phase2_opc_f1")),
            _fmt_score(row.get("phase2_tag_ocr_em")),
            _fmt_score(row.get("phase2_edge_f1")),
            _fmt_yn(row.get("phase2_dexpi_validates")),
            _fmt_money(row.get("cost_usd")),
            _fmt_minutes(row.get("wall_clock_min")),
        ]
        body_lines.append(" & ".join(cells) + " \\\\")

    # Macro row: per-kind means across the available fixtures (NaN-skipping
    # so partial-truth rows do not pollute OPC / edge F1). Cost is the corpus
    # total; wall-clock is the corpus total in minutes.
    def _mean(col: str) -> float:
        if col not in per_fixture.columns:
            return float("nan")
        return float(per_fixture[col].mean(skipna=True))

    def _sum(col: str) -> float:
        if col not in per_fixture.columns:
            return float("nan")
        return float(per_fixture[col].fillna(0).sum())

    n_truth = _sum("entity_count_truth")
    macro_cells = [
        "\\textbf{macro}",
        _fmt_int(n_truth),
        _fmt_score(_mean("phase2_equipment_f1")),
        _fmt_score(_mean("phase2_instrument_f1")),
        _fmt_score(_mean("phase2_opc_f1")),
        _fmt_score(_mean("phase2_tag_ocr_em")),
        _fmt_score(_mean("phase2_edge_f1")),
        _fmt_yn(_mean("phase2_dexpi_validates")),
        _fmt_money(_sum("cost_usd")),
        _fmt_minutes(_sum("wall_clock_min")),
    ]
    body_lines.append("\\midrule")
    body_lines.append(" & ".join(macro_cells) + " \\\\")

    return TABLE3_PREAMBLE + "\n".join(body_lines) + "\n" + TABLE3_EPILOGUE


# ---------------------------------------------------------------------------
# Convenience — write both tables to a directory
# ---------------------------------------------------------------------------


def write_tables(out_dir: Path, *, table2_wide: pd.DataFrame, table3: pd.DataFrame) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    p2 = out_dir / "table2.tex"
    p3 = out_dir / "table3.tex"
    p2.write_text(render_table2(table2_wide), encoding="utf-8")
    p3.write_text(render_table3(table3), encoding="utf-8")
    paths["table2"] = p2
    paths["table3"] = p3
    return paths
